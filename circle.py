import math


def area(r):

    ''' 
    Получает на вход радиус окружности r, возвращает площадь окружности
    Пример вызова: 
        area(1) -> 3.141592653589793  
    '''

    return math.pi * r * r


def perimeter(r):

    ''' 
    Получает на вход радиус окружности r, возвращает периметр окружности 
    Пример вызова: 
        perimeter(3) -> 18.84955592153876
    '''

    return 2 * math.pi * r

