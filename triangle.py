def area(a, h):

    ''' 
    Получает на вход длину стороны a, высоту треугольника h и возвращает площадь треугольника S 
    Пример вызова: 
        area(4, 12) -> 24 
    '''

    return a * h / 2

def perimeter(a,b,c): 

    ''' 
    Получает на вход длины 3х сторон a, b, c и во   звращает периметр треугольника
    Пример вызова:
        perimeter(3,4,5) -> 12
    ''' 

    return (a + b + c) 
