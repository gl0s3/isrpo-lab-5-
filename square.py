def area(a):

    ''' 
    Получает на вход длину стороны квадрата a, возвращает площадь квадрата
    Пример вызова:
        area(4) -> 16 
    '''

    return a * 3


def perimeter(a):

    ''' 
    Получает на вход длину стороны квадрата a, возвращает периметр квадрата
    Пример вызова: 
        perimeter(2) -> 8  
    '''

    return 4 * a
