def area(a, b):

    ''' 
    Получает на вход длины стороны a и b, возвращает площадь прямоугольника 
    Пример вызова: 
        area(1, 2) -> 2
    
    '''

    return a * b 
def perimeter(a, b):

    ''' 
    Получает на вход длины стороны a и b, возвращает периметр прямоугольника
    Пример вызова:
        perimeter(14, 2) -> 32 
    '''
    
    return  2 * (a + b)